#!/usr/bin/env python3
"""Independent reference for the pii-eval Wilson vectors (not run in CI).

Computes the Wilson score interval endpoint with the textbook formula in
Python's decimal module at 120 significant digits (correctly rounded sqrt),
then rounds ONCE, half up, to the requested number of decimal places. It
shares no code and no algebraic rearrangement with the Rust implementation
(which uses exact integer arithmetic): this script evaluates

    centre = (p + z^2 / (2n)) / (1 + z^2 / n)
    spread = (z / (1 + z^2 / n)) * sqrt(p (1 - p) / n + z^2 / (4 n^2))

exactly as the oracle's `wilson()` does, but in decimal instead of binary64.

Usage: python3 wilson_reference.py            # prints the Rust table
"""
from decimal import Decimal, getcontext, ROUND_HALF_UP

getcontext().prec = 120


def quant(value: Decimal, places: int) -> Decimal:
    return value.quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)


def wilson(k: int, n: int, z: Decimal, direction: str, places: int) -> int:
    p = Decimal(k) / Decimal(n)
    nn = Decimal(n)
    scale = 1 + z * z / nn
    centre = (p + z * z / (2 * nn)) / scale
    spread = (z / scale) * (p * (1 - p) / nn + z * z / (4 * nn * nn)).sqrt()
    raw = centre + spread if direction == "upper" else centre - spread
    raw = min(Decimal(1), max(Decimal(0), raw))
    return int(quant(raw, places) * (10 ** places))


def point(k: int, n: int, places: int) -> int:
    return int(quant(Decimal(k) / Decimal(n), places) * (10 ** places))


MAXI = (1 << 53) - 1
# (k, n, z mantissa, z scale, places)
CASES = [
    (0, 1, 196, 2, 6), (1, 1, 196, 2, 6),
    (0, 4, 196, 2, 6), (1, 4, 196, 2, 6), (2, 4, 196, 2, 6), (3, 4, 196, 2, 6), (4, 4, 196, 2, 6),
    (0, 10, 196, 2, 6), (5, 10, 196, 2, 6), (10, 10, 196, 2, 6),
    (3, 20, 196, 2, 1), (3, 20, 196, 2, 2), (1, 8, 196, 2, 2), (1, 8, 196, 2, 3),
    (7, 30, 196, 2, 6), (29, 30, 196, 2, 6),
    (1, 6, 196, 2, 12), (5, 6, 196, 2, 12),
    (0, 1000, 196, 2, 6), (1000, 1000, 196, 2, 6), (13, 1000, 196, 2, 6),
    (1, 3, 100, 2, 6), (1, 3, 1, 0, 6), (2, 7, 2576, 3, 6), (2, 7, 5, 1, 6),
    (333_333_333, 1_000_000_000, 196, 2, 6),
    (1, 1_000_000_000, 196, 2, 12), (999_999_999, 1_000_000_000, 196, 2, 12),
    (500_000_000_000, 1_000_000_000_000, 196, 2, 12),
    (0, 1_000_000_000_000, 196, 2, 12), (1_000_000_000_000, 1_000_000_000_000, 196, 2, 12),
    (1, MAXI, 196, 2, 12), (MAXI - 1, MAXI, 196, 2, 12), (MAXI // 2, MAXI, 196, 2, 6),
    (MAXI // 3, MAXI, 196, 2, 12),
    (0, MAXI, 196, 2, 12), (MAXI, MAXI, 196, 2, 12),
    (MAXI // 7, MAXI, MAXI, 12, 12), (1, 4, MAXI, 12, 6),
]


def main() -> None:
    print("// Generated by wilson_reference.py (Python decimal, 120 digits). Do not edit by hand.")
    print("// (k, n, z mantissa, z scale, places, point, upper, lower)")
    print("pub type WilsonVector = (u64, u64, u64, u8, u8, u64, u64, u64);")
    print("pub const WILSON_VECTORS: &[WilsonVector] = &[")
    for k, n, zm, zs, places in CASES:
        z = Decimal(zm).scaleb(-zs)
        print(f"    ({k}, {n}, {zm}, {zs}, {places}, {point(k, n, places)}, "
              f"{wilson(k, n, z, 'upper', places)}, {wilson(k, n, z, 'lower', places)}),")
    print("];")


if __name__ == "__main__":
    main()
