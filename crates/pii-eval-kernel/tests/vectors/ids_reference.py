#!/usr/bin/env python3
"""Independent reference for the pii-eval variant-id, seed and sha256-pattern vectors
(not run in CI; run once, output committed as ids_vectors.rs).

It implements docs/adr/0007-method-generation-and-variant-provenance.md from the written
specification with hashlib only. It shares no code with the Rust kernel, and the expected
values below are never copied from Rust output.

Specification recap (ADR 0007):
  preimage(fields)      = for each field: 4-byte big-endian length, then its UTF-8 bytes
  variant id            = slot + "-" + sha256(preimage(["pii-eval.variant-id/1", case_id, slot])).hex[:24]
  seed (pii-seed-v1)    = sha256(preimage(["pii-eval.variant-seed/1", generator, str(version),
                                           case_seed, case_id, slot])).hex            (64 digits)
  seed (legacy-case-seed) = case_seed
  sha256-pattern        : the oracle's materializePiiEvidenceCandidate; each 'D'/'A' of the pattern takes
                          the first 8 hex digits of sha256("<seed>/<n>") as an unsigned integer v,
                          n counting substitutions from 0: 'D' -> str(v % 10), 'A' -> chr(65 + v % 26).

Usage: python3 ids_reference.py > ids_vectors.rs
"""
import hashlib
import struct


def preimage(fields):
    out = b""
    for f in fields:
        raw = f.encode("utf-8")
        out += struct.pack(">I", len(raw)) + raw
    return out


def sha_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def variant_id(case_id: str, slot: str) -> str:
    return slot + "-" + sha_hex(preimage(["pii-eval.variant-id/1", case_id, slot]))[:24]


def pii_seed_v1(generator: str, version: int, case_seed: str, case_id: str, slot: str) -> str:
    return sha_hex(preimage(["pii-eval.variant-seed/1", generator, str(version), case_seed, case_id, slot]))


def pattern(seed: str, pat: str) -> str:
    out, token = [], 0
    for ch in pat:
        if ch not in "DA":
            out.append(ch)
            continue
        v = int(sha_hex(f"{seed}/{token}".encode("utf-8"))[:8], 16)
        token += 1
        out.append(str(v % 10) if ch == "D" else chr(65 + v % 26))
    return "".join(out)


def rs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


PREIMAGES = [["ab", "c"], ["a", "bc"], [""], ["pii-eval.variant-id/1", "case-a", "authored"]]
IDS = [
    ("case-a", "authored"),
    ("aa-b", "c-d"),
    ("aa", "b-c-d"),  # same concatenation "aa-b-c-d" as the pair above; must give a different id
    ("email-reserved-documentation-controls", "frame-sensitive"),
    ("c" * 80, "s" * 48),
    ("zz", "mutated"),
]
SEEDS = [
    ("pii-generator", 1, "case-seed.1", "case-a", "mutated"),
    ("pii-generator", 2, "case-seed.1", "case-a", "mutated"),
    ("pii-generator", 1, "case-seed.2", "case-a", "mutated"),
    ("pii-generator", 1, "case-seed.1", "case-b", "mutated"),
    ("pii-generator", 1, "case-seed.1", "case-a", "frame-sensitive"),
    ("g2", 10, "S" * 64, "case-a", "authored"),
]
PATTERNS = [
    ("seed-one", "SYNTHETIC-DDDD"),
    ("pii-benign-collision-v1/example", "DDD-DD-DDDD"),
    ("seed-two", "AADDA-x-DA"),
    ("seed-two", "no substitutions"),
    ("", "DDDDDDDD"),
]

print("// Generated by ids_reference.py (Python hashlib). Do not edit by hand.")
print("// preimage vectors: (fields, sha256 hex of the preimage)")
print("pub const PREIMAGE_VECTORS: &[(&[&str], &str)] = &[")
for fields in PREIMAGES:
    print(f"    (&[{', '.join(rs(f) for f in fields)}], {rs(sha_hex(preimage(fields)))}),")
print("];")
print("// variant id vectors: (case id, slot, variant id)")
print("pub const VARIANT_ID_VECTORS: &[(&str, &str, &str)] = &[")
for c, s in IDS:
    print(f"    ({rs(c)}, {rs(s)}, {rs(variant_id(c, s))}),")
print("];")
print("// pii-seed-v1 vectors: (generator, generator version, case seed, case id, slot, seed)")
print("pub const SEED_VECTORS: &[(&str, u32, &str, &str, &str, &str)] = &[")
for g, v, cs, c, s in SEEDS:
    print(f"    ({rs(g)}, {v}, {rs(cs)}, {rs(c)}, {rs(s)}, {rs(pii_seed_v1(g, v, cs, c, s))}),")
print("];")
print("// sha256-pattern vectors: (seed, pattern, materialized value)")
print("pub const PATTERN_VECTORS: &[(&str, &str, &str)] = &[")
for sd, p in PATTERNS:
    print(f"    ({rs(sd)}, {rs(p)}, {rs(pattern(sd, p))}),")
print("];")
